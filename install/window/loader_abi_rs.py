"""loader_abi.rs: tools/package/loader_abi.py's constants as Rust, so the installer and the packaging share one source.

    loader_abi_rs.py OUT

Every upper-case name becomes a `pub const`: integers as u64, strings as &str, bytes as a u8 array, a tuple or list of
integers as a tuple or array of u64, a list of (name, start, size) as a slice, a dict of integers as one constant per
key (NAME_KEY). Any other kind of value fails the build, so a new one is never silently left out.
"""

import sys
from pathlib import Path

import loader_abi


def _int(value: int) -> str:
    if not 0 <= value < 1 << 64:
        raise SystemExit(f'loader_abi_rs: {value} is not a u64')
    return f'0x{value:X}' if value > 9 else str(value)


def _ints(values: list[int] | tuple[int, ...]) -> bool:
    return all(type(v) is int for v in values)


def _ranges(values: list) -> bool:
    return all(type(v) is tuple and len(v) == 3 and type(v[0]) is str and _ints(v[1:]) for v in values)


def _form(value: object) -> tuple[str, str] | None:
    """Return the Rust type and value of an integer, string, bytes, or tuple or list of integers."""
    if type(value) is int:
        return 'u64', _int(value)
    if type(value) is str:
        return '&str', f'"{value}"'
    if type(value) is bytes:
        return f'[u8; {len(value)}]', f'[{", ".join(_int(b) for b in value)}]'
    if type(value) is tuple and len(value) > 1 and _ints(value):
        return f'({", ".join(["u64"] * len(value))})', f'({", ".join(map(_int, value))})'
    if type(value) is list and _ints(value):
        return f'[u64; {len(value)}]', f'[{", ".join(map(_int, value))}]'
    return None


def _const(name: str, value: object) -> list[str]:
    form = _form(value)
    if form:
        return [f'pub const {name}: {form[0]} = {form[1]};']
    if type(value) is list and _ranges(value):
        rows = [f'    ("{n}", {_int(start)}, {_int(size)}),' for n, start, size in value]
        return [f'pub const {name}: &[(&str, u64, u64)] = &[', *rows, '];']
    if type(value) is dict and all(type(k) is str and type(v) is int for k, v in value.items()):
        return [f'pub const {name}_{key.upper()}: u64 = {_int(v)};' for key, v in value.items()]
    raise SystemExit(f'loader_abi_rs: no Rust form for {name} ({type(value).__name__})')


def generate() -> str:
    """Return loader_abi.rs."""
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        "//! tools/package/loader_abi.py's constants, generated by install/window/loader_abi_rs.py.",
        '',
    ]
    for name, value in vars(loader_abi).items():
        if name.isupper() and not name.startswith('_'):
            lines += _const(name, value)
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    Path(sys.argv[1]).write_text(generate())
